#!/usr/bin/env node
/**
 * Generates `src/ipc/generated.ts` from `schema/studio-ipc.schema.json` (plan §11.0, IC-01).
 *
 * The schema is itself generated from STUDIO_METHODS in `src/studio/protocol.mjs`, so the protocol keeps a
 * single source of truth: Node → JSON Schema → TypeScript. The output is deterministic (methods sorted by
 * name, LF line endings) so the drift test can compare it byte for byte.
 *
 * Usage: `node scripts/gen-ipc-types.mjs` writes the file; `--stdout` prints it instead.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const APP_ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCHEMA = fileURLToPath(new URL('../../../schema/studio-ipc.schema.json', import.meta.url));
const OUTPUT = `${APP_ROOT}src/ipc/generated.ts`;

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));

const literal = value => (typeof value === 'string' ? `'${value.replaceAll("'", "\\'")}'` : JSON.stringify(value));
const key = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name));

/** JSON Schema subset used by protocol.mjs → TypeScript type expression. */
function toType(node, indent) {
  if (!node || typeof node !== 'object') return 'unknown';
  if (Array.isArray(node.enum)) return node.enum.map(literal).join(' | ');
  if ('const' in node) return literal(node.const);
  switch (node.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array': {
      const item = toType(node.items, indent);
      return /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case 'object': {
      const properties = Object.entries(node.properties ?? {});
      if (properties.length === 0)
        return node.additionalProperties === false ? 'Record<string, never>' : 'Record<string, unknown>';
      const required = new Set(node.required ?? []);
      const pad = '  '.repeat(indent + 1);
      const lines = properties.map(([name, child]) => {
        return `${pad}readonly ${key(name)}${required.has(name) ? '' : '?'}: ${toType(child, indent + 1)};`;
      });
      return `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`;
    }
    default:
      return 'unknown';
  }
}

const methods = Object.entries(schema.methods).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const requests = methods.filter(([, entry]) => entry.direction === 'host->engine' && !entry.notification);
const hostNotifications = methods.filter(([, entry]) => entry.direction === 'host->engine' && entry.notification);
const events = methods.filter(([, entry]) => entry.direction === 'engine->host');

const out = [];
out.push(
  '// GENERATED by scripts/gen-ipc-types.mjs from schema/studio-ipc.schema.json. Do not edit: run `npm run gen:ipc`.',
);
out.push('');
out.push(`export const STUDIO_PROTOCOL_VERSION = ${schema.properties.protocolVersion.const} as const;`);
out.push(`export const MAX_FRAME_BYTES = ${schema.properties.maxFrameBytes.const} as const;`);
out.push('');
out.push('/** Engine requests the frontend may issue through the host (`engine_call`). */');
out.push('export interface EngineRequestParams {');
for (const [name, entry] of requests) {
  out.push(`  readonly ${literal(name)}: ${toType(entry.paramsSchema, 1)};`);
}
out.push('}');
out.push('');
out.push('/** Host → engine notifications (no result). */');
out.push('export interface EngineNotificationParams {');
for (const [name, entry] of hostNotifications) {
  out.push(`  readonly ${literal(name)}: ${toType(entry.paramsSchema, 1)};`);
}
out.push('}');
out.push('');
out.push('/** Engine → host events forwarded to the frontend. */');
out.push('export interface EngineEventPayloads {');
for (const [name, entry] of events) {
  out.push(`  readonly ${literal(name)}: ${toType(entry.paramsSchema, 1)};`);
}
out.push('}');
out.push('');
out.push('export type EngineRequest = keyof EngineRequestParams;');
out.push('export type EngineEvent = keyof EngineEventPayloads;');
out.push('');
out.push(
  `export const ENGINE_REQUESTS: readonly EngineRequest[] = [${requests.map(([name]) => literal(name)).join(', ')}];`,
);
out.push(`export const ENGINE_EVENTS: readonly EngineEvent[] = [${events.map(([name]) => literal(name)).join(', ')}];`);
out.push('');

const text = out.join('\n');
if (process.argv.includes('--stdout')) process.stdout.write(text);
else writeFileSync(OUTPUT, text);
